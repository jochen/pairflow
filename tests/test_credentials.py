def test_resolve_secret_from_settings_js_double_quotes(tmp_path: Path):
    settings = tmp_path / "settings.js"
    settings.write_text(textwrap.dedent("""
        module.exports = {
            credentialSecret: "my-double-quoted-secret",
        };
    """))
    assert credentials.resolve_secret(tmp_path) == "my-double-quoted-secret"


def test_resolve_secret_from_settings_js_single_quotes(tmp_path: Path):
    settings = tmp_path / "settings.js"
    settings.write_text("    credentialSecret: 'single-quoted',\n")
    assert credentials.resolve_secret(tmp_path) == "single-quoted"


def test_resolve_secret_false_returns_none(tmp_path: Path):
    settings = tmp_path / "settings.js"
    settings.write_text("credentialSecret: false,\n")
    assert credentials.resolve_secret(tmp_path) is None


def test_resolve_secret_falls_back_to_config_runtime_json(tmp_path: Path):
    """No settings.js → read _credentialSecret from .config.runtime.json."""
    cfg = tmp_path / ".config.runtime.json"
    cfg.write_text(json.dumps({"_credentialSecret": "runtime-secret"}))
    assert credentials.resolve_secret(tmp_path) == "runtime-secret"


def test_resolve_secret_falls_back_to_config_json(tmp_path: Path):
    """No settings.js or .config.runtime.json → read .config.json."""
    cfg = tmp_path / ".config.json"
    cfg.write_text(json.dumps({"_credentialSecret": "legacy-secret"}))
    assert credentials.resolve_secret(tmp_path) == "legacy-secret"


def test_resolve_secret_prefers_settings_js_over_config(tmp_path: Path):
    """settings.js takes precedence over .config.runtime.json."""
    settings = tmp_path / "settings.js"
    settings.write_text("credentialSecret: 'from-settings',\n")
    cfg = tmp_path / ".config.runtime.json"
    cfg.write_text(json.dumps({"_credentialSecret": "from-config"}))
    assert credentials.resolve_secret(tmp_path) == "from-settings"


def test_resolve_secret_raises_when_nothing_found(tmp_path: Path):
    """When no source provides a secret, a helpful ValueError is raised."""
    with pytest.raises(ValueError, match="Cannot determine the Node-RED credential secret"):
        credentials.resolve_secret(tmp_path)


def test_resolve_secret_settings_js_without_credential_secret_falls_through(tmp_path: Path):
    """A settings.js without credentialSecret key falls through to config files."""
    settings = tmp_path / "settings.js"
    settings.write_text("module.exports = { adminAuth: {} };\n")
    cfg = tmp_path / ".config.json"
    cfg.write_text(json.dumps({"_credentialSecret": "fallback"}))
    assert credentials.resolve_secret(tmp_path) == "fallback"


