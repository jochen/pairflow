# Crypto: encrypt / decrypt round-trips
# ---------------------------------------------------------------------------


def test_encrypt_decrypt_round_trip_with_secret():
    """Encrypting then decrypting returns the original store."""
    secret = "my-test-secret"
    store = {"nodeabc": {"username": "admin", "password": "hunter2"}}

    encrypted = credentials.encrypt_store(store, secret)
    assert "$" in encrypted

    decrypted = credentials.decrypt_store(encrypted, secret)
    assert decrypted == store


def test_encrypt_decrypt_round_trip_plaintext():
    """With secret=None, encrypt_store returns the store unchanged."""
    store = {"nodeabc": {"token": "open-secret"}}
    encrypted = credentials.encrypt_store(store, secret=None)
    assert encrypted == store  # no $ wrapper

    decrypted = credentials.decrypt_store(encrypted, secret=None)
    assert decrypted == store


def test_encrypt_produces_correct_format():
    """Encrypted value must be: 32 hex IV chars + valid base64 ciphertext."""
    import base64 as _b64

    secret = "format-check"
    encrypted = credentials.encrypt_store({"n": {"k": "v"}}, secret)
    encoded = encrypted["$"]

    # IV: 32 hex chars = 16 bytes
    iv_hex = encoded[:32]
    assert len(iv_hex) == 32
    assert bytes.fromhex(iv_hex)  # must be valid hex

    # Ciphertext: valid base64
    b64_part = encoded[32:]
    decoded = _b64.b64decode(b64_part)
    assert len(decoded) > 0


def test_decrypt_store_passthrough_when_no_dollar_key():
    """A plaintext store (no $ key) is returned as-is even when secret is set."""
    store = {"node1": {"token": "plaintext-value"}}
    # This can happen with a freshly initialised NR that hasn't written its
    # first encrypted cred file yet.
    result = credentials.decrypt_store(store, secret="some-secret")
    assert result == store


def test_encrypt_store_empty_dict():
    """Encrypting an empty store must round-trip back to an empty store."""
    secret = "empty-secret"
    enc = credentials.encrypt_store({}, secret)
    dec = credentials.decrypt_store(enc, secret)
    assert dec == {}


# ---------------------------------------------------------------------------
# Regression fixture: guard against algorithm changes
#
# The fixture below was generated by running this Python snippet once:
#
#   import hashlib, base64, json
#   from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
#
#   secret = "reg-test-secret"
#   store   = {"node1": {"pw": "abc"}}
#   key     = hashlib.sha256(secret.encode()).digest()
#   iv      = bytes.fromhex("deadbeefcafebabe0011223344556677")
#   pt      = json.dumps(store).encode()
#   c       = Cipher(algorithms.AES(key), modes.CTR(iv))
#   enc     = c.encryptor()
#   ct      = enc.update(pt) + enc.finalize()
#   print("deadbeefcafebabe0011223344556677" + base64.b64encode(ct).decode())
#   # → "deadbeefcafebabe0011223344556677b7DqpeHBlBLo/m151jQero7d649ZeFKa"
#
# If this test fails the crypto algorithm was accidentally changed.
# ---------------------------------------------------------------------------

REGRESSION_SECRET = "reg-test-secret"
REGRESSION_STORE = {"node1": {"pw": "abc"}}
REGRESSION_ENCODED = "deadbeefcafebabe0011223344556677b7DqpeHBlBLo/m151jQero7d649ZeFKa"


def test_decrypt_known_fixture():
    """Decrypting the hardcoded fixture returns the known store."""
    raw = {"$": REGRESSION_ENCODED}
    result = credentials.decrypt_store(raw, REGRESSION_SECRET)
    assert result == REGRESSION_STORE


def test_encrypt_with_known_iv_matches_fixture(monkeypatch):
    """Encrypting with a deterministic IV reproduces the fixture string."""
    fixed_iv = bytes.fromhex("deadbeefcafebabe0011223344556677")
    monkeypatch.setattr("os.urandom", lambda n: fixed_iv[:n])

    enc = credentials.encrypt_store(REGRESSION_STORE, REGRESSION_SECRET)
    assert enc["$"] == REGRESSION_ENCODED


