@pytest.fixture
def cred_setup(tmp_path: Path):
    """Return (cred_file, secret, initial_store)."""
    secret = "test-cred-secret"
    store = {"existing": {"token": "old-token"}}
    cred_file = tmp_path / "flows_cred.json"
    cred_file.write_text(
        json.dumps(credentials.encrypt_store(store, secret)),
    )
    return cred_file, secret, store


def test_set_credentials_creates_new_entry(cred_setup):
    cred_file, secret, _ = cred_setup
    result = credentials.set_node_credentials(
        cred_file, "newnode", {"api_key": "xyz"}, secret,
    )
    assert result["node_id"] == "newnode"
    assert result["keys_set"] == ["api_key"]
    assert result["merged"] is False  # no prior entry

    store = credentials.read_store(cred_file, secret)
    assert "api_key" in store["newnode"]
    # Value is present in the store (unencrypted form after decrypt).
    assert store["newnode"]["api_key"] == "xyz"


def test_set_credentials_merge_adds_to_existing(cred_setup):
    cred_file, secret, _ = cred_setup
    # First write one field.
    credentials.set_node_credentials(
        cred_file, "multifield", {"username": "u"}, secret,
    )
    # Now merge a second field.
    result = credentials.set_node_credentials(
        cred_file, "multifield", {"password": "p"}, secret, merge=True,
    )
    assert result["merged"] is True
    assert result["keys_set"] == ["password"]

    store = credentials.read_store(cred_file, secret)
    assert store["multifield"]["username"] == "u"
    assert store["multifield"]["password"] == "p"


def test_set_credentials_replace_overwrites_all(cred_setup):
    cred_file, secret, _ = cred_setup
    credentials.set_node_credentials(
        cred_file, "multifield", {"username": "u", "password": "p"}, secret,
    )
    credentials.set_node_credentials(
        cred_file, "multifield", {"token": "t"}, secret, merge=False,
    )
    store = credentials.read_store(cred_file, secret)
    assert "token" in store["multifield"]
    assert "username" not in store["multifield"]


def test_set_credentials_creates_file_when_absent(tmp_path: Path):
    """set_node_credentials creates the cred file if it does not yet exist."""
    cred_file = tmp_path / "new_cred.json"
    assert not cred_file.exists()
    secret = "new-file-secret"

    result = credentials.set_node_credentials(
        cred_file, "nodeX", {"key": "val"}, secret,
    )
    assert cred_file.exists()
    assert result["node_id"] == "nodeX"
    store = credentials.read_store(cred_file, secret)
    assert store["nodeX"]["key"] == "val"


def test_set_credentials_optimistic_lock(cred_setup):
    """Concurrent modification of the cred file raises ConcurrentModificationError."""
    cred_file, secret, store = cred_setup
    mtime = writer.current_mtime(cred_file)

    # Simulate external modification.
    time.sleep(0.05)
    cred_file.write_text(
        json.dumps(credentials.encrypt_store({"changed": {"by": "other"}}, secret)),
    )

    with pytest.raises(writer.ConcurrentModificationError):
        writer.atomic_write_json(
            cred_file,
            credentials.encrypt_store(store, secret),
            expected_mtime=mtime,
        )


